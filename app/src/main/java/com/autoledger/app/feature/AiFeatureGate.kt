package com.autoledger.app.feature

/**
 * AI 判定功能的**上线门控**（单一开关，UI 与数据两侧共用）。
 *
 * ## 当前状态：入口隐藏，功能完整保留
 *
 * 用户决定「AI 功能暂时先不上线，开关先隐藏，功能保留」。因此这里只藏 UI 入口，
 * **实现一行没删** —— 配置存储（`app_settings` 四列）、密钥保管（`AiKeyVault`，
 * Keystore 包裹）、判定链路（`feature:ai` + `TypeRefiner` 接线）、超时与回落护栏、
 * 隐私文案条件化，全部原样保留在仓库里。
 *
 * ## 为什么不只把设置卡片藏起来
 *
 * 只隐藏 UI 是**不够的**：若数据库里残留了 `aiEnabled = true`
 * （例如导入旧备份、或将来入口开放过又关闭），采集链路照样会发请求、
 * 照样把通知正文发出去 —— 那就变成"用户看不到开关，但数据在出网"，是最坏的一种状态。
 * 所以同一个常量被两处读：
 * ① `CaptureAndSettings.kt` 读它决定**是否渲染**设置卡与密钥提示；
 * ② `AppContainer.kt` 读它决定 **AI 判定器是否真的启用**（且此时连 Keystore 都不碰）。
 *
 * ## 为什么"藏起来"不能替代"决定要不要上线"
 *
 * 这套功能的风险集中在两处，都不是靠隐藏入口能消除的：
 * ① 判定链路插在采集主路径上（超时/失败必须静默回落本地规则）；
 * ② 开启后通知正文会离开设备 —— 与产品此前对外承诺的「不发任何数据上云」直接冲突，
 * 需要用户明确知情并同意（隐私分区那条条件化文案就是为此准备的）。
 * 是否上线是**产品决策**，不该由一次代码提交顺带带过。
 *
 * ## 入口隐藏期间的行为保证
 *
 * `aiEnabled` 默认 `false`、`typeRefiner` 默认 `null`，门控再叠一层 ⇒
 * **不发起任何网络请求、通知原文不离开设备**，与 v1.1.6 行为完全一致。
 *
 * ## 恢复上线
 *
 * 把 [ENTRY_VISIBLE] 改为 `true` 即可，无需其他改动（UI 与数据侧会同时恢复）。
 */
internal object AiFeatureGate {
    /** AI 判定设置卡是否在设置页展示、且判定链路是否真的启用。false = 入口隐藏、功能保留。 */
    const val ENTRY_VISIBLE: Boolean = false
}
