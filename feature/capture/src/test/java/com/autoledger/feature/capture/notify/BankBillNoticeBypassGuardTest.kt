/**
 * 账单提醒拒绝的**绕过面**回归护栏（v1.1.16，QA 复核后的 P1）。
 *
 * ## 为什么再开一个文件
 * `BankExpenseRegressionGuardTest`（工程师）与 `BankBillNoticeIndependentAuditTest`（QA）
 * 用的都是「关键词 + 金额 + 无流出动词」这套判据**成立**的样本。QA 复核发现这条判据
 * 有两个可绕过面，两个都实测可复现：
 *  ① 负向断言只看「有没有『消费』这两个字」，不看它在句中是动词还是名词 ——
 *     `…应还款额1,451.50元（含上月未出账单消费），到期还款日…` 里的「消费」是**名词**，
 *     却把整条正文放行了（实测 -145150 分）；
 *  ② 正向关键词是 5 条短语的白名单，交行「最后还款日」、招行「本期应还 / 账单已出」、
 *     建行「本期账单金额」全部漏在外面（实测 -210000 / -523680 分）。
 *
 * ## 收紧后的判据（生产实现，见 `DefaultNotificationRules.BANK_BILL_NOTICE_REJECT`）
 * ```
 * (?s)\A
 *   (?=.*(?:应还|待还金额|本期应还|最低还款额|到期还款日|最后还款日|账单已出
 *           |本期账单金额|账单金额|本期账单应还|本期应付))
 *   (?=.*\d[\d.,]*\s?元)
 *   (?!.*(?:消费|支出|扣款|取款|支付成功|交易成功|已消费)
 *         \s*(?:[（(][^）)]{0,12}[)）])?\s*[，,：:]?\s*(?:金额|人民币|RMB|CNY)?\s*[:：]?\s*[¥￥]?\s*\d)
 * ```
 * 第三段从「**出现动词**」收紧成「**动词 + 紧邻金额**」：
 *  - `消费500元` / `消费金额1,200元` / `支付成功，金额12.00元` ⇒ 命中 ⇒ 不拒绝（真交易）；
 *  - `（含上月未出账单消费），到期还款日…` ⇒ 动词后面是「）」，不是数字 ⇒ 不命中 ⇒ 拒绝。
 * 动词与金额之间允许**一层受控括号**（≤12 字、必须自己配对），用来覆盖
 * `消费（财付通）39.80元` 这类通道标注；因为括号必须从「（」开始，
 * 「（含上月未出账单消费）」这种「括号在动词之前」的写法不会被它救回来（B1 / B15 钉住）。
 * 正向短语用**裸 `应还`**（`应还` ⊂ `应还款` ⊂ `应还款额`）：反向只写「应还款」会漏掉
 * 「应还1,451.50元」（B16 钉住）；它安全的前提是负向断言仍要求「动词 + 紧邻金额」。
 *
 * ## 已知限制（由 team-lead 统一写进 CHANGELOG，不在本文件断言）
 * 「金额在动词**之前**」的语序（`1,451.50元已消费，本期账单应还…`）、双层括号、
 * 括号内 >12 字、白名单以外的银行特异措辞、全角 / 中文数字金额 —— 均会被拒或不被识别，
 * 属于「宁可漏记也不虚增」的一侧。
 */
class BankBillNoticeBypassGuardTest {

    private val parser = NotificationParser()

    private fun describe(r: NotificationParser.ParseResult?): String =
        if (r == null) "null（整条被丢弃）"
        else "rule=${r.ruleId} dir=${r.direction} amount=${r.amountMinor} cp=${r.counterparty}"

    /** 短信通道（发件号码当 title）与 App 通道都必须**不入账**。 */
    private fun assertNotBookedBoth(tag: String, body: String) {
        val sms = parser.parse("sms:inbox", "95588", body)
        assertNull(sms, "$tag：账单提醒不得入账（sms 通道）\n  正文=$body\n  实际=${describe(sms)}")
        val app = parser.parse("com.icbc", "动账通知", body)
        assertNull(app, "$tag：账单提醒不得入账（App 通道，共用通用规则）\n  正文=$body\n  实际=${describe(app)}")
    }

    private fun assertExpense(tag: String, body: String, expectedMinor: Long) {
        val r = parser.parse("sms:inbox", "95588", body)
        assertNotNull(r, "$tag：真实交易不得被静默丢弃\n  正文=$body\n  实际=${describe(r)}")
        assertEquals("bank_generic_out", r.ruleId, "$tag：应命中银行支出规则\n  正文=$body\n  实际=${describe(r)}")
        assertEquals(Direction.OUT, r.direction, "$tag：方向不得反转\n  正文=$body\n  实际=${describe(r)}")
        assertEquals(expectedMinor, r.amountMinor, "$tag：金额必须为负\n  正文=$body\n  实际=${describe(r)}")
    }

    // ==================================================================
    // ① 绕过面之一：名词「消费」不再是豁免理由
    // ==================================================================

    @Test
    fun `B1 - 应还款额后带「含上月未出账单消费」仍不入账（名词消费不得放行）`() {
        assertNotBookedBoth(
            "B1 名词消费",
            "短信账单：您尾号6602的信用卡本期账单：人民币账户应还款额1,451.50元" +
                "（含上月未出账单消费），到期还款日为11月11日。【工商银行】",
        )
    }

    // ==================================================================
    // ② 绕过面之二：白名单短语补齐（交行 / 招行 / 建行）
    // ==================================================================

    @Test
    fun `B2 - 交行「本期账单金额 + 最后还款日」不入账`() {
        assertNotBookedBoth(
            "B2 交行",
            "【交通银行】您尾号9012信用卡本期账单金额2,100.00元，最后还款日10月28日。",
        )
    }

    @Test
    fun `B3 - 招行「账单已出 + 本期应还」不入账`() {
        assertNotBookedBoth(
            "B3 招行",
            "【招商银行】您尾号1234信用卡账单已出，本期应还5,236.80元，请于10月25日前还款。",
        )
    }

    @Test
    fun `B4 - 用户工行原样样本仍不入账（不得因收紧而回归）`() {
        assertNotBookedBoth(
            "B4 工行逐字",
            "短信账单：您尾号6602的信用卡本期账单（9月24日—10月23日）：人民币账户应还款额1,451.50元，" +
                "到期还款日为11月11日。其他币种账户余额均为0。登录工银e生活App查询账单明细。【工商银行】",
        )
    }

    // ==================================================================
    // ③ 结构化：账单 / 对账单 × 应还 / 待还 / 最低还款 / 最后还款 / 到期还款 × 金额
    //    逐条断言不入账（至少 6 条，覆盖新增的每一个关键短语）
    // ==================================================================

    @Test
    fun `B5 - 账单口径的各种常规措辞一律不入账`() {
        val samples = listOf(
            "B5a 应还总额/最后还款日" to
                "【交通银行】您尾号9012信用卡应还总额2,100.00元，最后还款日10月28日。",
            "B5b 待还金额/到期还款日" to
                "【农业银行】您尾号3456信用卡对账单待还金额880.00元，到期还款日10月30日。",
            "B5c 本期账单应还/最低还款额" to
                "【中国银行】您尾号7890信用卡本期账单应还1,200.00元，最低还款额120.00元。",
            "B5d 账单金额/到期还款日" to
                "【建设银行】您尾号5678龙卡信用卡账单金额3,280.00元，到期还款日为11月5日。",
            "B5e 本期应还/账单已出" to
                "【招商银行】本期账单已出，您尾号1234信用卡本期应还5,236.80元。",
            "B5f 应还金额/本期账单金额" to
                "【工商银行】您尾号6602信用卡本期账单金额9,999.00元，应还金额9,999.00元。",
        )
        samples.forEach { (tag, body) -> assertNotBookedBoth(tag, body) }
    }

    // ==================================================================
    // ④ 反向：把「动词 + 紧邻金额」的几种真实写法逐一钉住（防过度拒绝）
    // ==================================================================

    @Test
    fun `B6 - 消费 + 到期还款日尾缀仍是支出`() {
        assertExpense("B6a 还款日尾缀", "您尾号1234卡消费500元，到期还款日为10月25日。", -50_000L)
    }

    @Test
    fun `B7 - 消费 + 本期账单应还0元 仍是支出`() {
        assertExpense("B7 本期账单应还0元", "您尾号1234卡消费1,000元，本期账单应还0元。", -100_000L)
    }

    @Test
    fun `B8 - 支付成功 + 紧邻金额 仍是支出（逗号与「金额」字样都不得挡住）`() {
        assertExpense(
            "B8 支付成功，金额12.00元",
            "您尾号1234卡支付成功，金额12.00元，本期账单应还0元。",
            -1_200L,
        )
    }

    @Test
    fun `B9 - 消费金额1,200元 这种「动词+金额字样+数字」仍是支出`() {
        assertExpense(
            "B9 消费金额",
            "您尾号1234卡消费金额1,200元，本期账单应还1,200元。",
            -120_000L,
        )
    }

    @Test
    fun `B10 - 真实信用卡还款交易仍解析（账单拒绝不得误杀还款）`() {
        assertExpense("B10 还款交易", "您尾号1234信用卡还款1,000元，感谢使用。", -100_000L)
    }

    // ==================================================================
    // ⑤ 证伪：旧形状（裸动词负向断言）确实拦不住 B1 的样本
    //    生产常量是 private，无法直接取；这里用**旧的字面形状**证明「收紧是必要的」，
    //    生产侧的效果由上面 B1 的 null 断言体现。
    // ==================================================================

    @Test
    fun `B11 - 旧的裸动词负向断言拦不住「（含上月未出账单消费）」`() {
        val oldShape =
            """(?s)\A(?=.*(?:应还款额|应还金额|到期还款日|最低还款额|本期账单应还))""" +
                """(?=.*\d[\d.,]*\s?元)(?!.*(?:消费|支出|扣款|取款|支付成功|交易成功|已消费))"""
        val body = "短信账单：您尾号6602的信用卡本期账单：人民币账户应还款额1,451.50元" +
            "（含上月未出账单消费），到期还款日为11月11日。【工商银行】"

        assertFalse(
            Regex(oldShape).containsMatchIn(body),
            "前提不成立：旧形状本应被名词「消费」放行（即不拒绝）—— " +
                "若这里变绿说明样本或旧形状已被改动，请重新评估本用例",
        )
        // 生产规则必须拒绝它
        assertNotBookedBoth("B11 证伪", body)
    }

    // ==================================================================
    // ⑥ 「应还款」不带「额」的措辞（v1.1.17 补白名单）
    // ==================================================================

    @Test
    fun `B12 - 「信用卡应还款5,000元」不入账（应还款不带「额」）`() {
        // 复核漏网：正向短语表里原先只有「应还款额」，而 bodyMustContainAny 有裸词「还款」，
        // 于是这句被记成 -500000。改成「应还款」（是「应还款额」的前缀）后必须拒绝。
        assertNotBookedBoth("B12 应还款无额", "您尾号1234信用卡应还款5,000元，请及时还款。")
    }

    // ==================================================================
    // ⑦ 动词后接「一层受控括号」（v1.1.17 放宽）
    // ==================================================================

    @Test
    fun `B13 - 消费（财付通）39_80元 仍是支出（通道标注不得让真支出被丢）`() {
        // 修改前：负向断言要求「动词后紧跟数字」，「（财付通）」挡住 ⇒ 不算真交易 ⇒
        // 与「到期还款日」同文时被整条丢弃（实测 null，漏记一笔真支出）。
        // 修改后：允许一层 ≤12 字、自己配对的括号 ⇒ 命中 ⇒ 正常入账。
        assertExpense(
            "B13 括号通道",
            "您尾号1234卡消费（财付通）39.80元，到期还款日为10月25日。",
            -3_980L,
        )
    }

    // ==================================================================
    // ⑧ 对照组：本次「收紧 + 放宽」都不得越界（两条都不许变红）
    // ==================================================================

    @Test
    fun `B14 - 对照组：收紧侧与放宽侧各一条，语义都不得漂移`() {
        // 收紧侧（B1 原样复述）：括号在动词**之前**的名词性说明 ⇒ 仍是账单，必须拒绝。
        // 放宽侧（B7 原样复述）：动词后紧跟金额 ⇒ 仍是真支出，必须入账。
        assertNotBookedBoth(
            "B14a 收紧侧",
            "短信账单：您尾号6602的信用卡本期账单：人民币账户应还款额1,451.50元" +
                "（含上月未出账单消费），到期还款日为11月11日。【工商银行】",
        )
        assertExpense("B14b 放宽侧", "您尾号1234卡消费1,000元，本期账单应还0元。", -100_000L)
    }

    // ==================================================================
    // ⑨ 证伪：括号组是**必要**改动，而不是等价改写
    //     把括号组从现行形状里删掉，「消费（财付通）39.80元」的账单样本就会被拒。
    // ==================================================================

    @Test
    fun `B15 - 去掉括号组后「消费（财付通）39_80元」会被误拒（证明括号组必要）`() {
        val withParen =
            """(?s)\A(?=.*(?:应还款|应还金额|应还总额|待还金额|本期应还|最低还款额""" +
                """|到期还款日|最后还款日|账单已出|本期账单金额|账单金额|本期账单应还))""" +
                """(?=.*\d[\d.,]*\s?元)""" +
                """(?!.*(?:消费|支出|扣款|取款|支付成功|交易成功|已消费)""" +
                """\s*(?:[（(][^）)]{0,12}[)）])?\s*[，,：:]?\s*(?:金额|人民币|RMB|CNY)?""" +
                """\s*[:：]?\s*[¥￥]?\s*\d)"""
        val parenGroup = """(?:[（(][^）)]{0,12}[)）])?"""
        // 只删括号组，其余逐字保留 —— 这样「前提」不会因为别处改动而失效
        val withoutParen = withParen.replace(parenGroup, "")

        val realExpense = "您尾号1234卡消费（财付通）39.80元，到期还款日为10月25日。"
        assertFalse(
            Regex(withParen).containsMatchIn(realExpense),
            "现行形状必须**不**命中它（含括号组 ⇒ 视为真交易 ⇒ 不拒绝）",
        )
        assertTrue(
            Regex(withoutParen).containsMatchIn(realExpense),
            "前提不成立：去掉括号组后本应命中（⇒ 被当成账单拒绝）—— " +
                "若这里变红说明括号组已不再是必要成分，请重新评估本用例",
        )
        // 生产规则按现行形状：必须入账
        assertExpense("B15 证伪", realExpense, -3_980L)
    }

    // ==================================================================
    // ⑩ 白名单改裸 `应还` 后：账单明细里的「应还X元」必须被拒
    // ==================================================================

    @Test
    fun `B16 - 「本期账单交易明细：应还1_451_50元」不入账（裸应还）`() {
        // 漏网成因：`bodyMustContainAny` 里有裸词「交易」⇒ 能进规则；而白名单当时只有
        // 应还款 / 应还金额 / 应还总额 / 本期应还，**没有裸「应还」** ⇒ 这句被记成 -145150。
        // 现在白名单以裸 `应还`（是 `应还款` / `应还款额` 的前缀）兜底 ⇒ 必须拒绝。
        assertNotBookedBoth("B16 交易明细应还", "您尾号1234信用卡本期账单交易明细：应还1,451.50元。")
    }

    // ==================================================================
    // ⑪ 本轮改动的回归对照：白名单扩大后，四条既有语义一条都不许漂移
    //    （与 B1 / B7 / B12 / B13 同源，这里集中复述一遍，便于只读这一处就知道没改过头）
    // ==================================================================

    @Test
    fun `B17 - 改裸应还后：四条既有语义全部保持不变`() {
        // ① 账单口径（应还款，不带「额」）⇒ 拒绝
        assertNotBookedBoth("B17a 应还款无额", "您尾号1234信用卡应还款5,000元，请及时还款。")
        // ② 动词 + 括号通道 + 金额 ⇒ 真支出，入账
        assertExpense(
            "B17b 括号通道",
            "您尾号1234卡消费（财付通）39.80元，到期还款日为10月25日。",
            -3_980L,
        )
        // ③ 动词 + 紧邻金额（同文带账单短语）⇒ 真支出，入账
        assertExpense("B17c 本期账单应还0元", "您尾号1234卡消费1,000元，本期账单应还0元。", -100_000L)
        // ④ 括号在动词之前的名词性说明 ⇒ 仍是账单，拒绝
        assertNotBookedBoth(
            "B17d 名词消费",
            "短信账单：您尾号6602的信用卡本期账单：人民币账户应还款额1,451.50元" +
                "（含上月未出账单消费），到期还款日为11月11日。【工商银行】",
        )
    }
}
